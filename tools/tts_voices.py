"""List the voices of each text-to-speech model on your Tiiny, and check which `voice` values work through the API.

    python tools/tts_voices.py                        # every TTS model you've downloaded
    python tools/tts_voices.py --model hexgrad/Kokoro-82M
    python tools/tts_voices.py --md docs/VOICES.md    # also write the voice lists as Markdown

Needs TIINY_URL / TIINY_KEY (as for api_test.py) and a Wi-Fi/LAN address: the voice list comes from each model's own
port, which the USB link blocks. For every TTS model: load it, read its speakers, send `/v1/audio/speech` with voice
"alloy" (what OpenAI clients send by default), with no voice, and with the model's own first voice (or a voice
description for voice-design models), then unload it.
"""
import argparse
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

import api_test as at


def ok(code):
    return "works" if code and code < 300 else f"fails ({code})"


def probe(t, host, mid):
    port = t.running()[mid]["port"]
    try:
        cap = json.loads(urllib.request.urlopen(f"http://{host}:{port}/v1/capabilities", timeout=10).read())
    except OSError:
        sys.exit(f"Can't reach the model's own port {port}: use a Wi-Fi/LAN address for TIINY_URL, not USB.")
    speakers = cap.get("supported_speakers") or []
    body = {"model": mid, "input": "Hello from my Tiiny. This is a speech test.", "response_format": "wav", "language": "en"}

    def say(**extra):  # some models fail the first request after a load: retry once
        code = t.call("POST", "/v1/audio/speech", {**body, **extra}, raw=True, timeout=300)[0]
        return code if code < 300 else t.call("POST", "/v1/audio/speech", {**body, **extra}, raw=True, timeout=300)[0]

    r = {"model": mid, "alloy": say(voice="alloy"), "none": say(), "clone": bool(cap.get("support_voice_clone")),
         "design": bool(cap.get("support_voice_design")), "speakers": [], "tried": None, "tried_code": None,
         "languages": len(cap.get("supported_languages") or [])}
    if r["design"]:
        r["tried"], r["tried_code"] = 'instruct "A calm, warm female voice."', say(instruct="A calm, warm female voice.")
    elif cap.get("support_custom_voice") and speakers:
        r["speakers"] = speakers
        pick = next((s for s in speakers if s.lower().startswith("en")), speakers[0])
        r["tried"], r["tried_code"] = f"voice '{pick}'", say(voice=pick)
    return r


def show(r):
    lines = [f"  voice 'alloy' (OpenAI default): HTTP {r['alloy']}", f"  no voice at all: HTTP {r['none']}"]
    if r["tried"]:
        lines.append(f"  {r['tried']}: HTTP {r['tried_code']}")
    elif not r["speakers"]:
        lines.append("  no preset voices: clone only (send ref_audio + ref_text, see the audio-tts check)")
    if r["clone"]:
        lines.append("  also: voice cloning (ref_audio + ref_text)")
    if r["speakers"]:
        lines.append(f"  speakers ({len(r['speakers'])}): {', '.join(r['speakers'])}")
    print(f"\n{r['model']}\n" + "\n".join(lines), flush=True)


def write_md(path, found, tiiny_os):
    out = ["# Voices of the Tiiny's text-to-speech models", "",
           f"Generated by `python tools/tts_voices.py --md docs/VOICES.md` on {time.strftime('%Y-%m-%d')}, "
           f"TiinyOS {tiiny_os}: each model's own voice list, plus test requests through `POST /v1/audio/speech`. "
           "Regenerate it after a TiinyOS or model update.", "",
           "**`voice` must be one of the model's own voices.** OpenAI's default `alloy` fails on most models "
           "(500 \"The upstream TTS model failed.\"). Use the full model id as `model`. More in "
           "[API.md](API.md#text-to-speech-which-voice-to-send-2026-11-05-tiinyos-0138).", "",
           "| model | `voice: \"alloy\"` | no `voice` | tested | voices |", "|---|---|---|---|---|"]
    for r in found:
        tried = f"{r['tried']}: {ok(r['tried_code'])}" if r["tried"] else ("clone only" if r["clone"] else "-")
        kind = (f"{len(r['speakers'])} preset (below)" if r["speakers"] else "voice design (`instruct`)" if r["design"]
                else "clone only (`ref_audio` + `ref_text`)")
        out.append(f"| `{r['model']}` | {ok(r['alloy'])} | {ok(r['none'])} | {tried} | {kind} |")
    for r in found:
        if r["speakers"]:
            out += ["", f"## {r['model']} ({len(r['speakers'])} voices)", "", ", ".join(f"`{s}`" for s in r["speakers"])]
    Path(path).write_text("\n".join(out) + "\n", "utf-8", newline="\n")
    print(f"\nwrote {path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--model", help="one model id instead of all downloaded TTS models")
    ap.add_argument("--md", help="also write the results as Markdown to this file (e.g. docs/VOICES.md)")
    a = ap.parse_args()
    t = at.Tiiny(*at.device())
    have = t.ok("GET", "/api/v1/models/?including_downloading=false")
    have = have.get("data", have) if isinstance(have, dict) else have
    models = [a.model] if a.model else sorted(m["id"] for m in have if m.get("type") == "Text-to-Speech")
    if not models:
        sys.exit("No text-to-speech models downloaded.")
    host = urllib.parse.urlparse(t.url).hostname
    before = set(t.running())
    found = []
    for mid in models:
        try:
            t.load(mid)
            found.append(probe(t, host, mid))
            show(found[-1])
        finally:
            if mid not in before:
                t.ok("POST", f"/api/v1/models/{urllib.parse.quote(mid, safe='')}/stop", {}, timeout=180)
    if a.md:
        write_md(a.md, found, t.ok("GET", "/api/v1/sys/device_info").get("tiiny_os"))


if __name__ == "__main__":
    main()
